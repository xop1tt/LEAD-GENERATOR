#!/usr/bin/env python3
"""Заглушки для XAML на Linux.

XAML-компилятор WinUI работает только на Windows, поэтому на Linux C#-код приложения проверяется так:
для каждого *.xaml создаётся частичный класс с полями x:Name и пустым InitializeComponent. Настоящая
сборка с XAML — в CI на Windows. Скрипт заодно проверяет, что обработчики событий из XAML есть в коде
страницы, и что первое имя в выражениях {x:Bind ...} существует в коде (или в типе x:DataType).

Использование: gen_stubs.py <папка приложения> <файл заглушек .cs>
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

X = "http://schemas.microsoft.com/winfx/2006/xaml"
DEFAULT_NS = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
EVENTS = {
    "Click", "Tapped", "DoubleTapped", "RightTapped", "SelectionChanged", "TextChanged", "Loaded", "Unloaded", "SizeChanged",
    "ItemClick", "KeyDown", "KeyUp", "Toggled", "ValueChanged", "Checked", "Unchecked", "LostFocus", "GotFocus",
    "PointerPressed", "PointerMoved", "PointerReleased", "PointerEntered", "PointerExited", "PointerCaptureLost", "Closed", "Opening", "Opened",
    "Closing", "ItemInvoked", "QuerySubmitted", "SuggestionChosen", "Invoked", "ContainerContentChanging", "DragItemsStarting",
    "PrimaryButtonClick", "SecondaryButtonClick", "CloseButtonClick", "ColorChanged", "SelectorBarSelectionChanged", "ActualThemeChanged",
    "PasswordChanged", "Activated", "Expanding", "Collapsed", "Expanded", "TextChanging", "SelectionChanging", "ElementPrepared",
    "CheckedChanged", "IsPaneOpenChanged", "BackRequested", "PaneClosing", "PaneOpening", "DropDownClosed", "DropDownOpened", "Holding",
}


def local(tag: str) -> str:
    return tag.split("}", 1)[1] if "}" in tag else tag


def ns_of(tag: str) -> str:
    return tag[1:].split("}", 1)[0] if tag.startswith("{") else ""


def main() -> int:
    app_dir = Path(sys.argv[1])
    out = Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    problems: list[str] = []
    blocks: list[str] = []
    skip_parents = {"DataTemplate", "ControlTemplate", "Style", "ItemsPanelTemplate"}
    for xaml in sorted(app_dir.rglob("*.xaml")):
        if any(p in ("obj", "bin") for p in xaml.parts):
            continue
        text = xaml.read_text(encoding="utf-8")
        try:
            root = ET.fromstring(text)
        except ET.ParseError as e:
            problems.append(f"{xaml}: XAML не разбирается: {e}")
            continue
        cls = root.attrib.get(f"{{{X}}}Class")
        if not cls:
            continue
        ns, _, name = cls.rpartition(".")
        fields: list[str] = []

        def walk(el: ET.Element, inside_template: bool) -> None:
            tag = local(el.tag)
            nm = el.attrib.get(f"{{{X}}}Name")
            if nm and not inside_template:
                if "." in tag:
                    return
                el_ns = ns_of(el.tag)
                if el_ns.startswith("using:"):
                    type_name = el_ns[len("using:"):] + "." + tag
                else:
                    type_name = tag
                fields.append(f"        internal {type_name} {nm} = null!;")
            for child in el:
                walk(child, inside_template or tag in skip_parents)

        walk(root, False)
        code_file = xaml.with_suffix(".xaml.cs")
        code = code_file.read_text(encoding="utf-8") if code_file.exists() else ""
        # обработчики событий
        for m in re.finditer(r'\s([A-Za-z]+)="([A-Za-z_][A-Za-z0-9_]*)"', text):
            attr, val = m.group(1), m.group(2)
            if attr in EVENTS and not re.search(r"\b" + re.escape(val) + r"\s*\(", code):
                problems.append(f"{xaml.name}: обработчик {attr}=\"{val}\" не найден в {code_file.name}")
        # {x:Bind ...} вне шаблонов данных: первое имя должно существовать в коде
        stripped = re.sub(r"<DataTemplate.*?</DataTemplate>", "", text, flags=re.S)
        for m in re.finditer(r"\{x:Bind\s+([^,}\s]+)", stripped):
            path = m.group(1)
            if path.startswith(("Path=", "Mode=")):
                path = path.split("=", 1)[1]
            first = re.split(r"[.(\[]", path, 1)[0]
            if ":" in first or not first or first in ("x", "local"):
                continue
            if not re.search(r"\b" + re.escape(first) + r"\b", code):
                problems.append(f"{xaml.name}: {{x:Bind {path}}}: имя {first} не найдено в {code_file.name}")
        blocks.append(
            f"namespace {ns}\n{{\n    partial class {name}\n    {{\n        private void InitializeComponent() {{ }}\n"
            + "\n".join(fields)
            + "\n    }\n}\n"
        )
    header = (
        "// <auto-generated/>\n#nullable enable\n"
        "using Microsoft.UI.Xaml;\nusing Microsoft.UI.Xaml.Controls;\nusing Microsoft.UI.Xaml.Controls.Primitives;\n"
        "using Microsoft.UI.Xaml.Documents;\nusing Microsoft.UI.Xaml.Shapes;\n"
    )
    out.write_text(header + "\n".join(blocks), encoding="utf-8")
    for p in problems:
        print("ПРОБЛЕМА:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
